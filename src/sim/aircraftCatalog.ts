import {AircraftCategory, AircraftId, EngineAudioProfile} from './types';

export interface AircraftModelPart {
  url: string;
  /** Offset in AC3D pre-rotation space [x, y, z] */
  offset?: [number, number, number];
  /** Rotation in AC3D pre-rotation space [rx, ry, rz] radians */
  rotation?: [number, number, number];
  /** Optional spinner / prop flag */
  isPropAttachment?: boolean;
  /** Optional engine pod zone tag */
  forceZone?: 'engines' | 'gear' | 'tail' | 'leftWing' | 'rightWing' | 'fuselage';
}

export interface AircraftLivery {
  id: string;
  name: string;
  carrier: string;
  textureUrl: string;
  accentHex: string;
}

export interface FlightModelParams {
  massKg: number;
  wingAreaM2: number;
  wingspanM: number;
  lengthM: number;
  heightM: number;
  aspectRatio: number;
  oswaldE: number;
  maxThrustN: number;
  afterburnerBoost: number; // e.g. 0.45 for Concorde / 0.65 for F-16, 0 otherwise
  propThrustFactor: number; // 0 for jet, >0 for turboprop/piston low-speed efficiency
  stallAoaDeg: number;
  clZero: number;
  clAlphaPerDeg: number;
  clFlapMax: number;
  cdZero: number;
  pitchAuthority: number;
  rollAuthority: number;
  yawAuthority: number;
  pitchStability: number;
  gearWheelbaseM: number;
  gearTrackM: number;
  hasRetractableGear: boolean;
  hasReverseThrust: boolean;
  hasFlaps: boolean;
  isSupersonicDelta: boolean;
  isProp: boolean;
  cruiseMach: number;
  vMaxKnots: number;
  approachSpeedKnots: number;
  cameraChaseDist: number;
  cockpitOffset: [number, number, number];
  wingCamOffset: [number, number, number];
  wingCamLook: [number, number, number];
  engineCount: number;
  engineLabel: string;
}

export interface AircraftVariant {
  id: string;
  name: string;
  badge: string;
  summary: string;
  fuselageLengthScale?: number;
  flightOverrides: Partial<FlightModelParams>;
}

export interface AircraftSpec {
  id: AircraftId;
  name: string;
  shortName: string;
  manufacturer: string;
  era: string;
  category: AircraftCategory;
  summary: string;
  audioProfile: EngineAudioProfile;
  /** Orientation rotation applied to convert model coordinates to Three.js (-Z forward, +Y up, +X right) */
  modelRotY: number;
  modelScale: number;
  /** Basenames of textures inside .ac files that represent the swappable airline livery */
  liveryTargetTextures: string[];
  parts: AircraftModelPart[];
  defaultLiveryId: string;
  liveries: AircraftLivery[];
  defaultVariantId: string;
  variants: AircraftVariant[];
  flight: FlightModelParams;
}

