export function getAircraftById(id: AircraftId): AircraftSpec {
  return AIRCRAFT_CATALOG.find((a) => a.id === id) ?? AIRCRAFT_CATALOG[0];
}

export function resolveAircraftVariant(
  spec: AircraftSpec,
  variantId?: string,
): {spec: AircraftSpec; variant: AircraftVariant} {
  const variant = spec.variants.find((v) => v.id === variantId) ?? spec.variants[0];
  const lenScale = variant.fuselageLengthScale ?? 1.0;
  const mergedFlight: FlightModelParams = {
    ...spec.flight,
    ...variant.flightOverrides,
  };
  if (lenScale !== 1.0) {
    mergedFlight.lengthM = Math.round(mergedFlight.lengthM * lenScale * 100) / 100;
    mergedFlight.gearWheelbaseM = Math.round(mergedFlight.gearWheelbaseM * lenScale * 100) / 100;
    mergedFlight.cockpitOffset = [
      mergedFlight.cockpitOffset[0],
      mergedFlight.cockpitOffset[1],
      Math.round(mergedFlight.cockpitOffset[2] * lenScale * 100) / 100,
    ];
  }
  return {
    spec: {
      ...spec,
      name: `${spec.manufacturer} ${variant.name}`,
      shortName: variant.name,
      flight: mergedFlight,
    },
    variant,
  };
}
